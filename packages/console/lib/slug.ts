/** Turn a human name into a commercetools-safe key: lowercase, a–z/0–9 with single hyphens. */
export function slugifyKey(s: string): string {
  return s
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 256);
}
